create table public.achievement_assessments (
    id bigint generated by default as identity primary key,
    school_id uuid not null,
    academic_year_id bigint not null,
    title text not null,
    assessment_type text not null default 'اختبار',
    subject text not null,
    grade text not null,
    assessment_date date not null,
    term text not null,
    teacher_id bigint,
    max_score numeric(12,4) not null,
    student_count integer not null default 0,
    average_score numeric(12,4),
    highest_score numeric(12,4),
    lowest_score numeric(12,4),
    mastery_threshold_pct numeric(5,2) not null default 60,
    mastered_count integer not null default 0,
    near_mastery_count integer not null default 0,
    intervention_count integer not null default 0,
    notes text,
    status text not null default 'draft',
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint achievement_assessments_title_nonblank check (btrim(title) <> ''),
    constraint achievement_assessments_subject_nonblank check (btrim(subject) <> ''),
    constraint achievement_assessments_grade_nonblank check (btrim(grade) <> ''),
    constraint achievement_assessments_term_nonblank check (btrim(term) <> ''),
    constraint achievement_assessments_max_score_check check (max_score > 0),
    constraint achievement_assessments_student_count_check check (student_count >= 0),
    constraint achievement_assessments_average_check
        check (average_score is null or (average_score >= 0 and average_score <= max_score)),
    constraint achievement_assessments_highest_check
        check (highest_score is null or (highest_score >= 0 and highest_score <= max_score)),
    constraint achievement_assessments_lowest_check
        check (lowest_score is null or (lowest_score >= 0 and lowest_score <= max_score)),
    constraint achievement_assessments_mastery_threshold_check
        check (mastery_threshold_pct between 0 and 100),
    constraint achievement_assessments_mastered_count_check check (mastered_count >= 0),
    constraint achievement_assessments_near_mastery_count_check check (near_mastery_count >= 0),
    constraint achievement_assessments_intervention_count_check check (intervention_count >= 0),
    constraint achievement_assessments_bucket_total_check
        check (mastered_count + near_mastery_count + intervention_count <= student_count),
    constraint achievement_assessments_status_check
        check (status in ('draft', 'recorded', 'reviewed')),
    constraint achievement_assessments_academic_year_fk
        foreign key (school_id, academic_year_id)
        references public.academic_years (school_id, id)
        on delete restrict,
    constraint achievement_assessments_teacher_fk
        foreign key (school_id, teacher_id)
        references public.teachers (school_id, id)
        on delete set null (teacher_id),
    constraint achievement_assessments_school_id_id_key unique (school_id, id)
);

create index idx_achievement_assessments_scope
    on public.achievement_assessments
