-- Marsad Al-Injazat — Phase S2-B3
-- Operational domains: meetings, curriculum planning, supervision, and achievement.
-- S2-B1 and S2-B2 must already exist. Runtime remains FastAPI/SQLite. RLS arrives in S2-C.

begin;

create table public.meetings (
    id bigint generated by default as identity primary key,
    school_id uuid not null,
    academic_year_id bigint not null,
    title text not null,
    meeting_type text not null default 'اجتماع قسم',
    meeting_date date not null,
    meeting_time time without time zone,
    location text,
    agenda text,
    discussion_summary text,
    notes text,
    status text not null default 'planned',
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint meetings_title_nonblank check (btrim(title) <> ''),
    constraint meetings_status_check check (status in ('planned', 'held', 'cancelled')),
    constraint meetings_academic_year_fk
        foreign key (school_id, academic_year_id)
        references public.academic_years (school_id, id)
        on delete restrict,
    constraint meetings_school_id_id_key unique (school_id, id)
);

create index idx_meetings_scope
    on public.meetings (school_id, academic_year_id, meeting_date desc, id desc);

create table public.meeting_attendees (
    school_id uuid not null,
    meeting_id bigint not null,
    teacher_id bigint not null,
    attendance_status text not null default 'present',
    created_at timestamptz not null default now(),
    constraint meeting_attendees_pkey primary key (meeting_id, teacher_id),
    constraint meeting_attendees_status_check
        check (attendance_status in ('present', 'absent', 'excused')),
    constraint meeting_attendees_meeting_fk
        foreign key (school_id, meeting_id)
        references public.meetings (school_id, id)
        on delete cascade,
    constraint meeting_attendees_teacher_fk
        foreign key (school_id, teacher_id)
        references public.teachers (school_id, id)
        on delete cascade
);

create index idx_meeting_attendees_meeting
    on public.meeting_attendees (school_id, meeting_id, teacher_id);
create index idx_meeting_attendees_teacher
    on public.meeting_attendees (school_id, teacher_id, meeting_id);

