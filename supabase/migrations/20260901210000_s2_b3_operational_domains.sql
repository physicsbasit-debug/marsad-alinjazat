    action_id bigint primary key,
    school_id uuid not null,
    metric_name text not null,
    unit text not null default '',
    direction text not null default 'higher_better',
    baseline_value numeric(18,6) not null,
    target_value numeric(18,6) not null,
    outcome_value numeric(18,6),
    measured_at date,
    reference_source text,
    reference_year text,
    reference_note text,
    notes text,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint achievement_action_metrics_direction_check
        check (direction in ('higher_better', 'lower_better')),
    constraint achievement_action_metrics_measurement_check
        check (
            (outcome_value is null and measured_at is null)
            or (outcome_value is not null and measured_at is not null)
        ),
    constraint achievement_action_metrics_action_fk
        foreign key (school_id, action_id)
        references public.achievement_actions (school_id, id)
        on delete cascade
);

create index idx_achievement_action_metrics_action
    on public.achievement_action_metrics (school_id, action_id);
create index idx_achievement_action_metrics_status
    on public.achievement_action_metrics (school_id, direction, outcome_value);

